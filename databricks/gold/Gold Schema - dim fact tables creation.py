from email.message import EmailMessage
from datetime import datetime
import smtplib

recipient_email = "bankingdataplatform.project@gmail.com"

# Store these in a Databricks secret scope before running this cell.
# Example scope/key names used below:
#   scope = "email"
#   key   = "gmail_sender"
#   key   = "gmail_app_password"
sender_email = dbutils.secrets.get("email", "gmail_sender")
sender_password = dbutils.secrets.get("email", "gmail_app_password")

created_gold_tables = [
    "banking_data_processing.gold.dim_customer",
    "banking_data_processing.gold.dim_account",
    "banking_data_processing.gold.fact_transactions",
    "banking_data_processing.gold.dim_loan",
    "banking_data_processing.gold.fact_loan_repayments",
    "banking_data_processing.gold.dim_employees",
    "banking_data_processing.gold.fact_fraud_alerts",
    "banking_data_processing.gold.dim_exchange_rates",
    "banking_data_processing.gold.dim_date"
]

run_timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
subject = f"Gold layer ingestion details - {run_timestamp}"
body = f"""
Hello Team,

The gold layer ingestion notebook has completed the table creation flow.

Notebook: Gold Schema - dim fact tables creation
Execution timestamp: {run_timestamp}
Target layer: banking_data_processing.gold

Tables included in this run:
- """ + "\n- ".join(created_gold_tables) + """

Please review the gold tables for downstream reporting and validation.

Regards,
Databricks Notebook Automation
"""

message = EmailMessage()
message["Subject"] = subject
message["From"] = sender_email
message["To"] = recipient_email
message.set_content(body)

with smtplib.SMTP("smtp.gmail.com", 587) as smtp:
    smtp.starttls()
    smtp.login(sender_email, sender_password)
    smtp.send_message(message)

print(f"Ingestion details email sent successfully to {recipient_email}")
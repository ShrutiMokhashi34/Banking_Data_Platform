# DBTITLE 1,Creating DIM_DATE
create_dim_date = spark.sql("""INSERT OVERWRITE TABLE banking_data_processing.gold.dim_date
SELECT
    CAST(DATE_FORMAT(date, 'yyyyMMdd') AS STRING) AS date_id,
    date,
    YEAR(date) AS year,
    QUARTER(date) AS quarter,
    MONTH(date) AS month,
    MONTHNAME(date) AS month_name,
    DAY(date) AS day,
    DAYOFWEEK(date) AS day_of_week,
    ((DAYOFWEEK(date) + 5) % 7) + 1 AS day_of_week_iso,
    WEEKOFYEAR(date) AS week_of_year

FROM
(
    SELECT
        EXPLODE(
            SEQUENCE(
                DATE '2020-01-01',
                DATE '2030-12-31',
                INTERVAL 1 DAY
            )
        ) AS date
);
""")

